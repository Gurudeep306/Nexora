#!/usr/bin/env node
/*
  Generates src/components/icon/packs/phosphor/<weight>.ts from the raw SVG
  assets in @phosphor-icons/core (devDependency), using the semantic map in
  packs/phosphor/map.ts. One module per weight → one lazy chunk per weight,
  so users only download the weight they use.

    node scripts/gen-phosphor-icons.mjs
*/
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'src/components/icon/packs/phosphor')
const assets = path.join(root, 'node_modules/@phosphor-icons/core/assets')
const WEIGHTS = ['thin', 'light', 'regular', 'bold', 'fill', 'duotone']

const map = fs.readFileSync(path.join(dir, 'map.ts'), 'utf8')
const entries = [...map.matchAll(/^\s+'?([\w-]+)'?: '([\w-]+)',$/gm)].map((m) => [m[1], m[2]])
if (!entries.length) throw new Error('no entries found in map.ts')

/* Round a decimal to 1 place without merging it into its neighbour: in path
   data "-" and a leading "." also separate numbers ("c0-.05", "l1.5.14"), so
   keep the sign, keep the leading-dot form, and add a space when a ".x"
   number rounds to an integer. */
const round = (n) => {
  const neg = n.startsWith('-')
  let s = String(Math.round(Math.abs(Number(n)) * 10) / 10)
  if (s.startsWith('0.')) s = s.slice(1)
  if (neg) return `-${s}`
  return n.startsWith('.') && !s.startsWith('.') ? ` ${s}` : s
}

const key = (k) => (/^[a-z]+$/.test(k) ? k : `'${k}'`)
let missing = 0
for (const w of WEIGHTS) {
  const lines = entries.map(([name, icon]) => {
    const file = path.join(assets, w, w === 'regular' ? `${icon}.svg` : `${icon}-${w}.svg`)
    if (!fs.existsSync(file)) {
      console.error(`missing ${w}/${icon} (for ${name})`)
      missing++
      return `  ${key(name)}: '',`
    }
    const svg = fs.readFileSync(file, 'utf8').trim()
    const inner = svg
      .replace(/^<svg[^>]*>/, '')
      .replace(/<\/svg>$/, '')
      // 1 decimal on the 256 grid is < 0.01px at icon sizes — and ~20% smaller.
      .replace(/ d="([^"]*)"/g, (_, d) => ` d="${d.replace(/-?\d*\.\d+/g, round)}"`)
    return `  ${key(name)}: '${inner.replace(/'/g, "\\'")}',`
  })
  const out = `/* GENERATED by scripts/gen-phosphor-icons.mjs from @phosphor-icons/core — do not edit. */
import type { IconName } from '../../names'

/** Inner SVG markup (256×256 viewBox, currentColor) per semantic name — Phosphor ${w}. */
const glyphs: Record<IconName, string> = {
${lines.join('\n')}
}
export default glyphs
`
  fs.writeFileSync(path.join(dir, `${w}.ts`), out)
}
if (missing) process.exit(1)
console.log(`phosphor: ${entries.length} names × ${WEIGHTS.length} weights`)
