/**
 * Cloudflare Pages control files, written into dist/ by the Vite build
 * (see `pagesFiles()` in vite.config.ts). The Express server ignores them, so
 * the single-host Render deploy is unaffected.
 *
 *   _redirects — send server-only paths (OAuth, uploads, the legacy admin
 *                pages) to the API host. Client routes need no rule: Pages
 *                falls back to index.html (SPA mode) when there's no 404.html.
 *   _headers   — caching + the same security headers the API's helmet sends,
 *                with the API origin added to connect-src.
 *
 * Both depend on VITE_API_URL (e.g. https://api.nexoraguru.in); with it unset
 * no redirects and only same-origin rules are written.
 */

const trim = (s: string | undefined) => String(s ?? '').trim().replace(/\/+$/, '')

/** Server-rendered paths that must be answered by the API host. */
const SERVER_PATHS = [
  '/auth/github',
  '/auth/github/callback',
  '/auth/google',
  '/auth/google/callback',
  '/uploads/*',
  '/studio',
  '/studio/*',
  '/studio.html',
  '/forgebuilder',
  '/forgebuilder.html',
  '/live-class',
  '/live-class.html',
  '/legacy',
]

export function pagesRedirects(apiUrl: string | undefined): string {
  const api = trim(apiUrl)
  const lines = ['# Generated by client/pages-files.ts at build time — edit that file, not dist/.']
  if (/^https?:\/\//.test(api)) {
    for (const p of SERVER_PATHS) {
      const to = p.endsWith('/*') ? `${api}${p.slice(0, -1)}:splat` : `${api}${p}`
      lines.push(`${p} ${to} 302`)
    }
  }
  // No "/* /index.html 200" line: Pages already serves index.html for any
  // path without a file when the build has no 404.html (its SPA mode), and
  // flags that rule as an infinite loop and ignores it.
  lines.push('')
  return lines.join('\n')
}

/** Mirrors the helmet CSP in src/server.js, plus the API host for fetch/websocket. */
export function contentSecurityPolicy(apiUrl: string | undefined): string {
  const api = trim(apiUrl)
  const connect = ["'self'"]
  if (/^https?:\/\//.test(api)) {
    connect.push(api, api.replace(/^http/, 'ws'))
  } else {
    connect.push('wss:', 'ws:')
  }
  // Browser error reports (only used when VITE_SENTRY_DSN is set).
  connect.push('https://*.ingest.sentry.io', 'https://*.ingest.us.sentry.io', 'https://*.ingest.de.sentry.io')
  const d: Record<string, string[]> = {
    'default-src': ["'self'"],
    'script-src': [
      "'self'",
      "'unsafe-inline'",
      "'unsafe-eval'",
      'https://cdn.jsdelivr.net',
      'https://cdnjs.cloudflare.com',
      'https://cdn.socket.io',
      'https://cdn.quilljs.com',
    ],
    'script-src-attr': ["'unsafe-inline'"],
    'style-src': [
      "'self'",
      "'unsafe-inline'",
      'https://fonts.googleapis.com',
      'https://cdn.jsdelivr.net',
      'https://cdnjs.cloudflare.com',
      'https://cdn.quilljs.com',
    ],
    'font-src': ["'self'", 'https://fonts.gstatic.com', 'https://cdn.jsdelivr.net', 'https://cdnjs.cloudflare.com', 'data:'],
    'img-src': ["'self'", 'data:', 'https:', 'blob:'],
    'media-src': ["'self'", 'https:', 'blob:', 'data:'],
    'connect-src': connect,
    'worker-src': ["'self'", 'blob:'],
    'frame-src': ["'self'", 'https://www.youtube.com', 'https://www.youtube-nocookie.com', 'https://player.vimeo.com'],
    'object-src': ["'none'"],
    'base-uri': ["'self'"],
    'form-action': ["'self'"],
    'frame-ancestors': ["'self'"],
  }
  const parts = Object.entries(d).map(([k, v]) => `${k} ${v.join(' ')}`)
  parts.push('upgrade-insecure-requests')
  return parts.join('; ')
}

export function pagesHeaders(apiUrl: string | undefined): string {
  return [
    '# Generated by client/pages-files.ts at build time — edit that file, not dist/.',
    '/*',
    `  Content-Security-Policy: ${contentSecurityPolicy(apiUrl)}`,
    '  X-Content-Type-Options: nosniff',
    '  X-Frame-Options: SAMEORIGIN',
    '  Referrer-Policy: strict-origin-when-cross-origin',
    '  Cross-Origin-Opener-Policy: same-origin',
    '  Strict-Transport-Security: max-age=31536000; includeSubDomains; preload',
    '',
    '# Content-hashed build output: cache for a year.',
    '/assets/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
    '# GATE figures and other public files: a day at the edge and in the browser.',
    '/gate-fig/*',
    '  Cache-Control: public, max-age=86400',
    '/images/*',
    '  Cache-Control: public, max-age=86400',
    '',
    '# The app shell must never be stale, or users would load old hashed chunks.',
    '/',
    '  Cache-Control: no-cache',
    '/index.html',
    '  Cache-Control: no-cache',
    '',
  ].join('\n')
}
