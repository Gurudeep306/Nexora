"""Check (and, with --write, regenerate) the vectors behind the PDS C labs.

Every program of lab_corpus.py is compiled with the system C compiler (common.run_c, -std=c11, in a
fresh temporary directory) and run; its real output and exit status go into lab_vectors_c.json,
which tests/gate-notes.test.js runs through client/src/gate/notes/labs/cLogic.ts (the interpreter
must print exactly the same bytes, or report an error for the "expect": "error" programs). The
presets each lab offers are written to client/src/gate/notes/labs/cPresets.ts with the compiler's
output, so the lab can show "what cc printed" next to its own trace.

    python3 content/gate-notes/_checks/pds/lab_vectors.py           # check: files are current
    python3 content/gate-notes/_checks/pds/lab_vectors.py --write   # regenerate
"""
import json
import sys

import common as C
from lab_corpus import P

VEC = C.ROOT / "content" / "gate-notes" / "_checks" / "pds" / "lab_vectors_c.json"
PRESETS = C.ROOT / "client" / "src" / "gate" / "notes" / "labs" / "cPresets.ts"

ids = [p["id"] for p in P]
assert len(ids) == len(set(ids)), "duplicate corpus ids"
vectors = []
for p in P:
    r = C.run_c(p["src"], stdin=p["input"])
    assert r.compiled, f"{p['id']} does not compile:\n{r.err}"
    if p["expect"] == "ok":
        assert r.status == 0, f"{p['id']}: exit status {r.status}"
    vectors.append({"id": p["id"], "src": p["src"], "input": p["input"], "expect": p["expect"], "cc": {"out": r.out, "status": r.status}})
vec_text = json.dumps({"compiler": "cc -std=c11 -O0", "vectors": vectors}, indent=1, ensure_ascii=False) + "\n"

pres = [dict(v, chapter=p["chapter"], title=p["title"]) for v, p in zip(vectors, P) if p["chapter"] and p["expect"] == "ok"]
lines = [
    "/*",
    "  Preset programs for the PDS C labs (C Tracer, Memory Inspector, Recursion Tracer).",
    "  GENERATED by content/gate-notes/_checks/pds/lab_vectors.py from lab_corpus.py — do not edit.",
    "  `cc` is the output of the program compiled with the system C compiler (cc -std=c11 -O0).",
    "*/",
    "export interface CPreset {",
    "  id: string",
    "  chapter: number",
    "  title: string",
    "  src: string",
    "  input: string",
    "  cc: string",
    "}",
    "",
    "export const C_PRESETS: CPreset[] = " + json.dumps(
        [{"id": v["id"], "chapter": v["chapter"], "title": v["title"], "src": v["src"], "input": v["input"], "cc": v["cc"]["out"]} for v in pres],
        indent=2, ensure_ascii=False).replace('"id"', "id").replace('"chapter"', "chapter").replace('"title"', "title").replace('"src"', "src").replace('"input"', "input").replace('"cc"', "cc"),
    "",
]
pre_text = "\n".join(lines)

if "--write" in sys.argv:
    VEC.write_text(vec_text)
    PRESETS.write_text(pre_text)
    print(f"wrote {len(vectors)} vectors and {len(pres)} presets")
else:
    assert VEC.exists() and VEC.read_text() == vec_text, "lab_vectors_c.json is stale: run lab_vectors.py --write"
    assert PRESETS.exists() and PRESETS.read_text() == pre_text, "cPresets.ts is stale: run lab_vectors.py --write"
    print(f"lab_vectors: {len(vectors)} programs compiled and run with cc; vectors and {len(pres)} presets current")
