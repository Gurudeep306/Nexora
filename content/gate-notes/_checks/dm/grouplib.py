"""Binary operations, semigroups, monoids and groups for the Discrete Mathematics checks (Chapter 5)
and the Group Lab.

A finite structure is (elements, op) where op(a, b) returns an element (or something outside the set,
which breaks closure). Everything is checked straight from the definitions by brute force.
"""
import itertools
import math


class Structure:
    def __init__(self, elems, op, name=""):
        self.E = list(elems)
        self.op = op
        self.name = name
        self.T = {(a, b): op(a, b) for a in self.E for b in self.E}

    def closed(self):
        return next(((a, b) for (a, b), c in self.T.items() if c not in self.E), None) is None

    def closure_failure(self):
        return next(((a, b, c) for (a, b), c in self.T.items() if c not in self.E), None)

    def associative_failure(self):
        if not self.closed():
            return None
        m = self.T
        for a, b, c in itertools.product(self.E, repeat=3):
            if m[(m[(a, b)], c)] != m[(a, m[(b, c)])]:
                return a, b, c
        return None

    def associative(self):
        return self.closed() and self.associative_failure() is None

    def commutative_failure(self):
        return next(((a, b) for a, b in itertools.combinations(self.E, 2) if self.T[(a, b)] != self.T[(b, a)]), None)

    def commutative(self):
        return self.commutative_failure() is None

    def identity(self):
        return next((e for e in self.E if all(self.T[(e, a)] == a and self.T[(a, e)] == a for a in self.E)), None)

    def inverse(self, a):
        e = self.identity()
        if e is None:
            return None
        return next((b for b in self.E if self.T[(a, b)] == e and self.T[(b, a)] == e), None)

    def invertible(self):
        return [a for a in self.E if self.inverse(a) is not None]

    def idempotents(self):
        return [a for a in self.E if self.T[(a, a)] == a]

    def kind(self):
        """'not closed' | 'magma' | 'semigroup' | 'monoid' | 'group' | 'abelian group'."""
        if not self.closed():
            return "not closed"
        if not self.associative():
            return "magma"
        if self.identity() is None:
            return "semigroup"
        if len(self.invertible()) < len(self.E):
            return "monoid"
        return "abelian group" if self.commutative() else "group"

    def is_group(self):
        return self.kind() in ("group", "abelian group")

    # ── group-only helpers ───────────────────────────────────────────────
    def power(self, a, k):
        e = self.identity()
        r = e
        for _ in range(k):
            r = self.T[(r, a)]
        return r

    def order(self, a):
        e = self.identity()
        x, k = a, 1
        while x != e:
            x = self.T[(x, a)]
            k += 1
            assert k <= len(self.E) + 1, "not a group"
        return k

    def generated(self, gens):
        e = self.identity()
        H = {e}
        frontier = [e]
        while frontier:
            x = frontier.pop()
            for g in gens:
                y = self.T[(x, g)]
                if y not in H:
                    H.add(y)
                    frontier.append(y)
        return frozenset(H)

    def generators(self):
        return [a for a in self.E if len(self.generated([a])) == len(self.E)]

    def cyclic(self):
        return bool(self.generators())

    def is_subgroup(self, H):
        H = set(H)
        if not H or not H <= set(self.E):
            return False
        return all(self.T[(a, self.inverse(b))] in H for a in H for b in H)

    def subgroups(self):
        """All subgroups (as frozensets), found as the subgroups generated by 1 or 2 elements and their joins."""
        subs = {self.generated([a]) for a in self.E}
        changed = True
        while changed:
            changed = False
            for A, B in itertools.combinations(list(subs), 2):
                J = self.generated(list(A | B))
                if J not in subs:
                    subs.add(J)
                    changed = True
        assert all(self.is_subgroup(H) for H in subs)
        return sorted(subs, key=lambda s: (len(s), sorted(map(str, s))))

    def left_cosets(self, H):
        out = []
        for a in self.E:
            c = frozenset(self.T[(a, h)] for h in H)
            if c not in out:
                out.append(c)
        return out

    def right_cosets(self, H):
        out = []
        for a in self.E:
            c = frozenset(self.T[(h, a)] for h in H)
            if c not in out:
                out.append(c)
        return out

    def table(self):
        return [[self.T[(a, b)] for b in self.E] for a in self.E]


def Zn(n):
    return Structure(range(n), lambda a, b: (a + b) % n, f"Z{n}")


def units(n):
    return [a for a in range(1, n) if math.gcd(a, n) == 1]


def Zn_star(n):
    U = units(n)
    return Structure(U, lambda a, b: a * b % n, f"Z{n}*")


def mult_mod(elems, n):
    return Structure(elems, lambda a, b: a * b % n, f"({elems}, ×{n})")


def from_table(elems, rows):
    idx = {e: i for i, e in enumerate(elems)}
    return Structure(elems, lambda a, b: rows[idx[a]][idx[b]])


def Sn(n):
    P = list(itertools.permutations(range(n)))
    # composition (p ∘ q)(x) = p(q(x))
    return Structure(P, lambda p, q: tuple(p[q[x]] for x in range(n)), f"S{n}")


def direct_product(G, H):
    E = [(a, b) for a in G.E for b in H.E]
    return Structure(E, lambda x, y: (G.T[(x[0], y[0])], H.T[(x[1], y[1])]), f"{G.name}×{H.name}")


def klein():
    return direct_product(Zn(2), Zn(2))


def isomorphic(G, H):
    if len(G.E) != len(H.E):
        return False
    return sorted(G.order(a) for a in G.E) == sorted(H.order(a) for a in H.E) and _iso_search(G, H)


def _iso_search(G, H):
    for p in itertools.permutations(H.E):
        f = dict(zip(G.E, p))
        if all(f[G.T[(a, b)]] == H.T[(f[a], f[b])] for a in G.E for b in G.E):
            return True
    return False


def order_mod(a, n):
    """Multiplicative order of a mod n (a coprime to n)."""
    assert math.gcd(a, n) == 1
    k, x = 1, a % n
    while x != 1:
        x = x * a % n
        k += 1
    return k


def phi(n):
    return sum(1 for k in range(1, n + 1) if math.gcd(k, n) == 1)


def square_and_multiply(a, k, n):
    """a^k mod n with the list of (bit, value) steps used by the lessons' ladder."""
    steps, r = [], 1
    for bit in bin(k)[2:]:
        r = r * r % n
        if bit == "1":
            r = r * a % n
        steps.append((bit, r))
    assert r == pow(a, k, n)
    return r, steps


def abelian_groups_count(n):
    """Number of abelian groups of order n up to isomorphism (product of partition counts of the exponents)."""
    from sympy import factorint
    from sympy.utilities.iterables import partitions
    out = 1
    for _, e in factorint(n).items():
        out *= sum(1 for _ in partitions(e))
    return out
