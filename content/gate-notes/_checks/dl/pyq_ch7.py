"""Check: every PYQ embedded in a Chapter 7 (beyond the core syllabus) lesson has a full teacher-style v2 solution in
src/gate/solutions (the reader shows it under the question):

- the approach names the concept tested ("Concept tested: …");
- at least two worked steps, a pitfalls list, and a verification or a shortcut;
- for MCQ/MSQ, an optionAnalysis entry for every option, and the options it marks correct are
  exactly the bank key;
- the solution's answer agrees with the bank key (matchesKey true) and its choice list (for
  MCQ/MSQ) is the key;
- the solution is generated by _sol_ch7.py (the file and src/gate/solutions agree), so the
  solution text in the repo is the reviewed source.

The keys themselves are recomputed from scratch in l7_01 … l7_03 (one per lesson).
"""
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import boollib as bl  # noqa: E402
import seqlib as cl  # noqa: E402
import _sol_ch7 as src  # noqa: E402

bank = bl.bank()
problems, n = [], 0
embedded = []
for f in sorted(cl.CH7.glob("[0-9][0-9]-*.md")):
    embedded += re.findall(r':::pyq\{id="([^"]+)"', f.read_text())
for qid in embedded:
    q = bank[qid]
    sol = json.loads((bl.ROOT / "src" / "gate" / "solutions" / f"{q['paper']}.json").read_text())["solutions"].get(qid)
    n += 1
    if not sol:
        problems.append(f"{qid}: no v2 solution")
        continue
    if qid not in src.SOLUTIONS or json.dumps(src.SOLUTIONS[qid], sort_keys=True) != json.dumps(sol, sort_keys=True):
        problems.append(f"{qid}: src/gate/solutions differs from _sol_ch7.py (run python3 content/gate-notes/_checks/dl/_sol_ch7.py)")
    if not sol["approach"].startswith("Concept tested"):
        problems.append(f"{qid}: approach must open with 'Concept tested: …'")
    if len(sol["steps"]) < 2:
        problems.append(f"{qid}: fewer than 2 steps")
    if not sol.get("pitfalls"):
        problems.append(f"{qid}: no pitfalls")
    if not (sol.get("verification") or sol.get("shortcut")):
        problems.append(f"{qid}: needs a verification or a shortcut")
    if not sol["answer"].get("matchesKey"):
        problems.append(f"{qid}: solution does not match the key")
    if q.get("options"):
        got = [o["option"] for o in sol.get("optionAnalysis", [])]
        want = [o["l"] for o in q["options"]]
        if got != want:
            problems.append(f"{qid}: optionAnalysis covers {got}, options are {want}")
        key = bl.key_letters(q["answer"])
        marked = sorted(o["option"] for o in sol.get("optionAnalysis", []) if o["correct"])
        if marked != key:
            problems.append(f"{qid}: optionAnalysis marks {marked} correct, the key is {key}")
        if sorted(sol["answer"].get("choice", [])) != key:
            problems.append(f"{qid}: answer.choice {sol['answer'].get('choice')} is not the key {key}")
    elif q["type"] == "NAT":
        a = str(q["answer"]).split(" to ")
        lo, hi = float(a[0]), float(a[-1])
        if not (lo <= sol["answer"].get("number", float("nan")) <= hi):
            problems.append(f"{qid}: answer.number {sol['answer'].get('number')} is not the key {q['answer']}")
extra = sorted(set(src.SOLUTIONS) - set(embedded))
if extra:
    problems.append(f"_sol_ch7.py has solutions for PYQs no lesson embeds: {extra}")
assert not problems, "\n" + "\n".join(problems)
print(f"pyq_ch7: {n} embedded PYQs have full teacher-style solutions matching the bank keys")
