#!/usr/bin/env node
/*
  Writes client/src/learn/content/ai/search.gen.ts: for every written AI topic,
  its pages and the section headings inside them. The site search and the
  course pages use it, so any small topic can be found by its words without
  loading a lesson. Run after writing or editing a topic:

    node scripts/ai-courses/build-search.mjs        (--check: fail if out of date)
*/
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const base = path.join(root, 'client/src/learn/content/ai')
const out = {}
for (const course of fs.readdirSync(base, { withFileTypes: true }).filter((d) => d.isDirectory()))
  for (const t of fs.readdirSync(path.join(base, course.name), { withFileTypes: true }).filter((d) => d.isDirectory())) {
    const idx = path.join(base, course.name, t.name, 'index.ts')
    if (!fs.existsSync(idx)) continue
    const topic = (await import(pathToFileURL(idx).href)).default
    out[topic.id] = topic.pages.map((p) => ({
      page: p.id,
      title: p.title,
      sections: [
        ...new Set(
          p.blocks.flatMap((b) => {
            if (b.t === 'md') return [...b.md.matchAll(/^#{2,3} (.+)$/gm)].map((m) => m[1].trim())
            if (b.t === 'derive' && b.title) return [b.title]
            if (b.t === 'stage') return [b.scene.title]
            return []
          }),
        ),
      ],
    }))
  }
const sorted = Object.fromEntries(Object.keys(out).sort().map((k) => [k, out[k]]))
const body = `/* Generated by scripts/ai-courses/build-search.mjs from the written AI topics. Do not edit. */
export interface AiPageIndex {
  page: string
  title: string
  /** Section headings, derivations and scenes on the page. */
  sections: string[]
}
export const AI_SEARCH: Record<string, AiPageIndex[]> = ${JSON.stringify(sorted, null, 2)}
`
const file = path.join(base, 'search.gen.ts')
if (process.argv.includes('--check')) {
  if ((fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '') !== body) {
    console.error('search.gen.ts is out of date: run node scripts/ai-courses/build-search.mjs')
    process.exit(1)
  }
  console.log('search.gen.ts is up to date')
} else {
  fs.writeFileSync(file, body)
  console.log(`wrote search.gen.ts: ${Object.keys(sorted).length} topics, ${Object.values(sorted).reduce((a, p) => a + p.length, 0)} pages`)
}
