#!/usr/bin/env node
/*
  Runs every Python example in the AI lessons on real CPython with the latest
  libraries, and records exactly what it printed (and any Matplotlib figures).
  The lessons show these recorded outputs; nothing is typed in by hand.

    PYTHON=/path/to/python3.15 node scripts/ai-courses/record-python.mjs
    node scripts/ai-courses/record-python.mjs --check   (fails if an example has no recording)

  The interpreter must be the version docs/ai-courses/PYTHON.md names (the
  latest stable Python, with NumPy, pandas, Matplotlib, scikit-learn, PyTorch).
*/
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const base = path.join(root, 'client/src/learn/content/ai')
const figDir = path.join(root, 'client/public/ai-py')
const outFile = path.join(base, 'python.gen.ts')
const { codeHash } = await import(pathToFileURL(path.join(root, 'client/src/learn/python/hash.ts')).href)

const blocks = []
for (const c of fs.readdirSync(base, { withFileTypes: true }).filter((d) => d.isDirectory()))
  for (const t of fs.readdirSync(path.join(base, c.name), { withFileTypes: true }).filter((d) => d.isDirectory())) {
    const idx = path.join(base, c.name, t.name, 'index.ts')
    if (!fs.existsSync(idx)) continue
    const topic = (await import(pathToFileURL(idx).href)).default
    for (const p of topic.pages) for (const b of p.blocks) if (b.t === 'python') blocks.push({ where: `${topic.id}/${p.id}`, code: b.code, stdin: b.stdin ?? '', hash: codeHash(b.code, b.stdin ?? '') })
  }

const old = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : ''
if (process.argv.includes('--check')) {
  const missing = blocks.filter((b) => !old.includes(`"${b.hash}"`))
  if (missing.length) {
    console.error(`${missing.length} Python example(s) have no recorded output (run record-python.mjs):\n` + missing.map((m) => `  ${m.where}`).join('\n'))
    process.exit(1)
  }
  console.log(`all ${blocks.length} Python examples are recorded`)
  process.exit(0)
}

const PY = process.env.PYTHON || '/tmp/py315/bin/python'
const RUNNER = `
import sys, io, os, traceback, importlib.metadata as md
src = sys.stdin.read()
code_src, _, stdin = src.partition('\\x00STDIN\\x00')
os.environ['MPLBACKEND'] = 'Agg'
buf = io.StringIO()
sys.stdout = sys.stderr = buf
sys.stdin = io.StringIO(stdin)
import linecache
# The source is not a file, so tell linecache about it: tracebacks then show the failing line.
linecache.cache['lesson.py'] = (len(code_src), None, code_src.splitlines(True), 'lesson.py')
ok = True
try:
    exec(compile(code_src, 'lesson.py', 'exec'), {'__name__': '__main__'})
except BaseException as e:
    ok = False
    te = traceback.TracebackException.from_exception(e)
    te.stack = traceback.StackSummary.from_list([f for f in te.stack if f.filename == 'lesson.py'])
    print(''.join(te.format()).rstrip())
figs = 0
if 'matplotlib.pyplot' in sys.modules:
    plt = sys.modules['matplotlib.pyplot']
    for n in plt.get_fignums():
        plt.figure(n).savefig(os.path.join(sys.argv[1], f'{sys.argv[2]}-{figs}.png'), dpi=110, bbox_inches='tight')
        figs += 1
sys.stdout = sys.__stdout__
import json
print(json.dumps({'out': buf.getvalue(), 'ok': ok, 'figures': figs}))
`
const ver = spawnSync(PY, ['-c', "import sys, importlib.metadata as m\nv={}\nfor p in ['numpy','pandas','matplotlib','scikit-learn','torch']:\n  try: v[p]=m.version(p)\n  except Exception: pass\nimport json; print(json.dumps({'python': sys.version.split()[0], **v}))"], { encoding: 'utf8' })
if (ver.status !== 0) throw new Error(`cannot run ${PY}: ${ver.stderr}`)
const env = JSON.parse(ver.stdout)
fs.mkdirSync(figDir, { recursive: true })
const rec = {}
for (const b of blocks) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'nx-py-'))
  // The same limit as the browser: a program still running after 10 seconds is stopped.
  const r = spawnSync(PY, ['-I', '-c', RUNNER, figDir, b.hash], { input: `${b.code}\u0000STDIN\u0000${b.stdin}`, cwd: tmp, encoding: 'utf8', timeout: 10000 })
  fs.rmSync(tmp, { recursive: true, force: true })
  if (r.error && r.error.code === 'ETIMEDOUT') {
    rec[b.hash] = { out: 'Stopped after 10 seconds: the program was still running (an endless loop).', ok: false, figures: 0 }
    console.log(`ERR ${b.where} ${b.hash} (stopped after 10 seconds)`)
    continue
  }
  if (r.status !== 0) throw new Error(`${b.where}: the runner failed\n${r.stderr}`)
  const res = JSON.parse(r.stdout.trim().split('\n').pop())
  rec[b.hash] = { out: res.out, ok: res.ok, figures: res.figures }
  console.log(`${res.ok ? 'ok ' : 'ERR'} ${b.where} ${b.hash}${res.figures ? ` (${res.figures} figure${res.figures > 1 ? 's' : ''})` : ''}`)
}
const body = `/* Generated by scripts/ai-courses/record-python.mjs: what each lesson example printed when run. Do not edit. */
export interface PyRecording {
  out: string
  /** false when the example ends in an error on purpose (the output shows it). */
  ok: boolean
  /** How many figures it drew (images in /ai-py/<hash>-<n>.png). */
  figures: number
}
/** The interpreter and libraries the outputs were recorded with. */
export const RECORDED_WITH: Record<string, string> = ${JSON.stringify(env, null, 2)}
export const PY_RECORDINGS: Record<string, PyRecording> = ${JSON.stringify(rec, null, 2)}
`
fs.writeFileSync(outFile, body)
console.log(`recorded ${blocks.length} examples with Python ${env.python}`)
