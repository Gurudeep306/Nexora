#!/usr/bin/env node
/*
  Writes client/src/learn/content/ai/web.gen.ts from docs/ai-courses/curriculum.json
  and web.json: every course, chapter and topic, with what each topic needs,
  what uses it and what is related. The site reads this to list every topic,
  link prerequisites across courses and search topic names, without loading
  any lesson. Run after editing the curriculum:

    node scripts/ai-courses/check-curriculum.mjs && node scripts/ai-courses/build-client-web.mjs

  `--check` fails (exit 1) when the file is out of date (used by the tests).
*/
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const cur = JSON.parse(fs.readFileSync(path.join(root, 'docs/ai-courses/curriculum.json'), 'utf8'))
const web = JSON.parse(fs.readFileSync(path.join(root, 'docs/ai-courses/web.json'), 'utf8'))
const node = new Map(web.nodes.map((n) => [n.id, n]))
const bookList = JSON.parse(fs.readFileSync(path.join(root, 'docs/ai-courses/sources/books.json'), 'utf8'))
const courseList = JSON.parse(fs.readFileSync(path.join(root, 'docs/ai-courses/sources/courses.json'), 'utf8')).courses
// Books, plus courses and official documentation (no authors line for those).
const books = Object.fromEntries([
  ...(Array.isArray(bookList) ? bookList : bookList.books).map((b) => [b.id, { title: b.title, authors: b.authors, url: b.url }]),
  ...courseList.map((c) => [c.id, { title: c.title, authors: '', url: c.url }]),
])

const nexusName = (id) => {
  const f = path.join(root, 'content/nexus', `${id}.json`)
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')).name : id
}
const courses = cur.courses.map((c) => ({
  id: c.id,
  title: c.title,
  blurb: c.blurb,
  story: c.story ?? '',
  nexus: c.nexus ? { id: c.nexus, name: nexusName(c.nexus) } : null,
  chapters: c.chapters.map((ch) => ({ title: ch.title, topics: ch.topics.map((t) => t.id) })),
}))
const topics = {}
for (const c of cur.courses)
  for (const ch of c.chapters)
    for (const t of ch.topics) {
      const n = node.get(t.id) ?? {}
      topics[t.id] = {
        title: t.title,
        course: c.id,
        chapter: ch.title,
        visual: t.visual ?? '',
        needs: t.needs ?? [],
        allNeeds: n.allNeeds ?? t.needs ?? [],
        usedBy: n.usedBy ?? [],
        related: n.related ?? [],
        gateDA: !!n.gateDA,
      }
    }

const body = `/* Generated by scripts/ai-courses/build-client-web.mjs from docs/ai-courses/curriculum.json and web.json. Do not edit. */
export interface AiCourse {
  id: string
  title: string
  blurb: string
  story: string
  /** The NexoraGuru subject this course grows from, if any (its page is /learn/<id>). */
  nexus: { id: string; name: string } | null
  chapters: { title: string; topics: string[] }[]
}
export interface AiTopicInfo {
  title: string
  course: string
  chapter: string
  /** The topic's signature animation, in one line. */
  visual: string
  needs: string[]
  /** Every topic needed on the way here, nearest first. */
  allNeeds: string[]
  usedBy: string[]
  related: string[]
  gateDA: boolean
}
export const AI_COURSES: AiCourse[] = ${JSON.stringify(courses, null, 2)}
export const AI_TOPIC_INFO: Record<string, AiTopicInfo> = ${JSON.stringify(topics, null, 2)}
/** The books, courses and official docs lessons may point to in "Read more". */
export const AI_BOOKS: Record<string, { title: string; authors: string; url: string }> = ${JSON.stringify(books, null, 2)}
`
const out = path.join(root, 'client/src/learn/content/ai/web.gen.ts')
if (process.argv.includes('--check')) {
  const now = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
  if (now !== body) {
    console.error('web.gen.ts is out of date: run node scripts/ai-courses/build-client-web.mjs')
    process.exit(1)
  }
  console.log('web.gen.ts is up to date')
} else {
  fs.writeFileSync(out, body)
  console.log(`wrote ${path.relative(root, out)}: ${courses.length} courses, ${Object.keys(topics).length} topics`)
}
