class Character:
    def __init__(self, pack, style=0.8, sex="auto", outfit=None):
        z = zipfile.ZipFile(pack)
        fr = np.load(io.BytesIO(z.read("frames.npz")))
        ident = json.loads(z.read("identity.json"))
        tri = [[int(q.split("/")[0]) - 1 for q in l.split()[1:4]] for l in z.read("face/mesh.obj").decode().splitlines() if l.startswith("f ")]
        body = [[list(map(float, q)) for q in b] for b in fr["body2d"]] if "body2d" in fr.files else None
        self.rig = Rig.build(fr["landmarks"], fr["blendshapes"], [str(n) for n in fr["blendshape_names"]], tri, body=body)
        self.names = self.rig.names
        self.ident = ident
        self.unit = float(ident.get("face", {}).get("scale_mm_per_outer_eye_unit", 88)) / 1000
        self.style = style
        col = ident.get("colours", {})
        g = lambda k, d: np.array(col.get(k, {}).get("rgb", d), np.float64)  # noqa: E731
        self.colours = {"skin": g("skin", [0.85, 0.7, 0.6]), "iris": g("iris", [0.3, 0.2, 0.15]), "lips": g("lips", [0.7, 0.45, 0.45]),
                        "brows": g("brows", [0.25, 0.2, 0.18]), "hair": g("hair", [0.15, 0.12, 0.1])}
        self.hair = ident.get("hair", {})
        if sex == "auto":
            sex = ident.get("body", {}).get("sex") or "neutral"
        self.sex = sex
        self.P = proportions(ident.get("body", {}).get("shoulder_width_m"), sex, head_iod_m=self.unit)
        self.S = build_skeleton(self.P)
        self.outfit = outfit or {"colour": [0.22, 0.32, 0.55], "sleeve": 0.8, "ease": 1.08}

    # face points (head units, rig axes) → metres, y up, z towards the camera, anime-stylised (linear in points)
    def stylise_map(self):
        """A 468x468 linear map M with styled = M @ points (per axis), built at the neutral face: every point
        moves by smooth weights towards/away from fixed centres (eyes, nose, mouth, jaw)."""
        F0 = self.rig.face(np.zeros(len(self.names)))
        s = self.style
        el, er = F0[[33, 133]].mean(0), F0[[263, 362]].mean(0)
        nose_tip, mouth = F0[1], F0[[13, 14]].mean(0)
        terms = []  # (centre, radius in units, scale xyz)
        terms += [(el, 0.42, np.array([1 + 0.32 * s, 1 + 0.42 * s, 1.0])), (er, 0.42, np.array([1 + 0.32 * s, 1 + 0.42 * s, 1.0]))]
        terms += [(nose_tip, 0.5, np.array([1 - 0.35 * s, 1 - 0.15 * s, 1 - 0.55 * s]))]
        terms += [(mouth, 0.45, np.array([1 - 0.18 * s, 1 - 0.1 * s, 1 - 0.2 * s]))]
        n = 468
        M = np.zeros((3, n, n))
        for ax in range(3):
            M[ax] = np.eye(n)
        for c, r, k in terms:
            d = np.linalg.norm(F0 - c, axis=1)
            w = np.clip(1 - (d / r) ** 2, 0, 1) ** 2
            # styled_i = p_i + w_i (k - 1)(p_i - c)  → linear in p_i (c fixed; its own movement ignored)
            for ax in range(3):
                M[ax][np.arange(n), np.arange(n)] += w * (k[ax] - 1)
        self._style_offsets = []
        for c, r, k in terms:
            d = np.linalg.norm(F0 - c, axis=1)
            w = np.clip(1 - (d / r) ** 2, 0, 1) ** 2
            self._style_offsets.append(-w[:, None] * (k - 1)[None] * c[None])
        # flatter face, softer jaw
        jaw = np.clip((F0[:, 1] - 0.6) / 0.8, 0, 1) * 0.1 * s
        for ax, f in ((0, 1 - jaw), (2, np.full(n, 1 - 0.12 * s))):
            M[ax] = M[ax] * f[:, None]
        return M, sum(self._style_offsets)

    def face_points(self, blend, M, off):
        F = self.rig.face(blend)
        P = np.stack([M[ax] @ F[:, ax] for ax in range(3)], 1) + off
        return P * self.unit * np.array([1, -1, -1]) * (1.0 + 0.22 * self.style)  # anime heads are larger

    def build(self):
        nb = len(self.names)
        M, off = self.stylise_map()
        P0 = self.face_points(np.zeros(nb), M, off)
        # 1. Face surface with eye and mouth openings
        Ff = np.array([t for t in self.rig.face_tri if not (set(t) <= set(EYE_L) or set(t) <= set(EYE_R) or set(t) <= set(INNER_LIPS))])
        # 2. Back of the head: columns from the oval to a pole behind, on an ellipsoid; each point follows its
        #    oval point by a falloff (so jaw movement carries to the cheeks and neck, not the skull)
        oval = OVAL
        Po = P0[oval]
        c = np.array([0, Po[:, 1].mean() + 0.01, Po[:, 2].mean() - 0.085])
        r = np.array([np.abs(Po[:, 0]).max() * 1.03, (Po[:, 1].max() - Po[:, 1].min()) / 2 * 1.08, 0.105])
        pole = np.array([0, 0.25, -1.0])
        pole /= np.linalg.norm(pole)
        R = 9
        shell, rows = [], []  # (column oval idx, falloff)
        for i, p in enumerate(Po):
            d0 = (p - c) / r
            n0 = np.linalg.norm(d0)
            d0 = d0 / n0
            for k in range(1, R + 1):
                t = k / (R + 1)
                ang = math.acos(np.clip(d0 @ pole, -1, 1))
                if ang < 1e-6:
                    d = d0
                else:
                    d = (math.sin((1 - t) * ang) * d0 + math.sin(t * ang) * pole) / math.sin(ang)
                rad = n0 * (1 - t) + 1.0 * t
                shell.append(c + r * d * rad)
                rows.append((oval[i], max(0.0, 1 - t * 2.5)))
        n_face = 468
        V0 = np.vstack([P0, np.array(shell), c + r * pole])
        pole_i = len(V0) - 1
        Fs = []
        cols = len(oval)
        sid = lambda i, k: n_face + i * R + (k - 1)  # noqa: E731
        for i in range(cols):
            j = (i + 1) % cols
            Fs += [(oval[i], sid(i, 1), oval[j]), (oval[j], sid(i, 1), sid(j, 1))]
            for k in range(1, R):
                Fs += [(sid(i, k), sid(i, k + 1), sid(j, k)), (sid(j, k), sid(i, k + 1), sid(j, k + 1))]
            Fs.append((sid(i, R), pole_i, sid(j, R)))
        Fh = np.vstack([Ff, np.array(Fs)])
        # orient: normals point away from the head centre
        cen = c
        A, B, C = V0[Fh[:, 0]], V0[Fh[:, 1]], V0[Fh[:, 2]]
        nrm = np.cross(B - A, C - A)
        flip = ((A + B + C) / 3 - cen) @ nrm.T if False else np.einsum("ij,ij->i", (A + B + C) / 3 - cen, nrm) < 0
        Fh[flip] = Fh[flip][:, [0, 2, 1]]
        # linear map from face points: base verts = G @ P (+ d)
        nv = len(V0)
        G = sps.lil_matrix((nv, 468))
        d = np.zeros((nv, 3))
        for i in range(468):
            G[i, i] = 1.0
        for k, (oi, f) in enumerate(rows):
            G[n_face + k, oi] = f
            d[n_face + k] = shell[k] - f * P0[oi]
        d[pole_i] = V0[pole_i]
        G = G.tocsr()
        # 3. Smooth: two Loop subdivisions
        S1, F1 = loop_subdivide(Fh, nv)
        S2, F2 = loop_subdivide(F1, S1.shape[0])
        S = S2 @ S1
        GH, dH = S @ G, S @ d
        head = {"G": GH, "d": dH, "F": F2}
        # 4. Brows, lashes (attached to face points: linear too)
        extras = []
        for upper, lower in (BROW_L, BROW_R):
            line = [(P0[a] + P0[b]) / 2 for a, b in zip(upper, lower)]
            w = [np.linalg.norm(P0[a] - P0[b]) * (0.55 if k else 0.7) * (1 - 0.35 * k / 4) for k, (a, b) in enumerate(zip(upper, lower))]
            Vb, Fb = ribbon(line, w, np.array([0, 0, 1.0]), lift=0.0012)
            extras.append(("brows", Vb, Fb, [upper, lower]))
        for lid in (UPPER_LID_L, UPPER_LID_R):
            line = [P0[k] for k in lid]
            w = [0.0012 + 0.0018 * math.sin(math.pi * k / (len(lid) - 1)) for k in range(len(lid))]
            w[0] = w[0] + 0.0012 if lid[0] in (33, 263) else w[0]
            Vl, Fl = ribbon(line, w, np.array([0, 0, 1.0]), lift=0.0008)
            extras.append(("lashes", Vl, Fl, [lid]))
        self.head, self.extras, self.M, self.off = head, extras, M, off
        return self

    def morphs(self):
        """Per-vertex position deltas of the head for each of the 52 expression values (value 1)."""
        nb = len(self.names)
        P0 = self.face_points(np.zeros(nb), self.M, self.off)
        out = []
        for k in range(nb):
            b = np.zeros(nb)
            b[k] = 1.0
            dP = self.face_points(b, self.M, self.off) - P0
            # anime faces exaggerate mouth and brows a little
            gain = 1.25 if self.names[k].startswith(("mouth", "jaw", "brow")) else 1.0
            out.append(self.head["G"] @ (dP * gain))
        return np.array(out)


def export(ch, out):
    """character.json + character.bin: meshes (positions, indices, skin, morphs), skeleton, colours."""
    os.makedirs(out, exist_ok=True)
    blob = bytearray()

    def put(arr, dt):
        nonlocal blob
        a = np.ascontiguousarray(arr, dtype=dt)
        while len(blob) % 4:
            blob.append(0)
        off = len(blob)
        blob += a.tobytes()
        return {"offset": off, "count": int(a.size), "type": "f32" if dt == np.float32 else "u32"}

    S = ch.S
    Rw, Pw = S.world()
    head_j = S.idx("head")
    nb = len(ch.names)
    P0 = ch.face_points(np.zeros(nb), ch.M, ch.off)
    # Place the head: eyes' midpoint at the head joint + offset (metres, head-joint frame)
    eye_mid = (P0[33] + P0[263]) / 2
    attach = Pw[head_j] + np.array([0, 0.088, 0.03]) - eye_mid
    meshes = []
    Vh = ch.head["G"] @ P0 + ch.head["d"] + attach
    morph = ch.morphs()
    meshes.append({"name": "head", "material": "skin", "pos": put(Vh, np.float32), "idx": put(ch.head["F"], np.uint32),
                   "bone": "head", "morphs": put(morph.astype(np.float32), np.float32)})
    for name, V, F, _ in ch.extras:
        meshes.append({"name": name, "material": name, "pos": put(V + attach, np.float32), "idx": put(F, np.uint32), "bone": "head"})
    # Eyes: behind the openings, radius from the eye width
    for side, ring in (("L", EYE_L), ("R", EYE_R)):
        ctr = P0[ring].mean(0)
        wdt = np.linalg.norm(P0[ring[0]] - P0[ring[8]])
        rad = wdt * 0.62
        c = ctr + np.array([0, 0, -rad * 0.62])
        Ve, Fe = sphere(c + attach, rad, 18)
        meshes.append({"name": f"eye{side}", "material": "eye", "pos": put(Ve, np.float32), "idx": put(Fe, np.uint32), "bone": "head",
                       "centre": (c + attach).tolist(), "radius": rad})
    # Mouth inside: a dark pocket behind the lips, upper teeth, tongue
    lip_ring = P0[INNER_LIPS]
    mc = lip_ring.mean(0)
    Vm, Fm = sphere(mc + np.array([0, 0, -0.022]) + attach, 0.024, 10)
    meshes.append({"name": "mouth", "material": "mouth", "pos": put(Vm, np.float32), "idx": put(Fm, np.uint32), "bone": "head"})
    teeth_line = [mc + np.array([x, 0.004, -0.006 - 0.02 * (x / 0.022) ** 2]) for x in np.linspace(-0.02, 0.02, 9)]
    Vt, Ft = ribbon(teeth_line, [0.006] * 9, np.array([0, 0, 1.0]))
    meshes.append({"name": "teeth", "material": "teeth", "pos": put(Vt + attach, np.float32), "idx": put(Ft, np.uint32), "bone": "head"})
    # Hair: anime locks
    hair = make_hair(ch, P0, attach)
    meshes.append({"name": "hair", "material": "hair", "pos": put(hair[0], np.float32), "idx": put(hair[1], np.uint32), "bone": "head"})
    # Body and clothes, skinned
    for t in tubes_for(ch.P, ch.outfit):
        if t.layer == "skin" and t.name == "torso":
            continue
        V, F, J, W = tube_rest(t, S, Rw, Pw)
        meshes.append({"name": t.name, "material": "cloth" if t.layer == "cloth" else "skin",
                       "colour": (t.colour.tolist() if t.colour is not None else None),
                       "pos": put(V, np.float32), "idx": put(F, np.uint32), "joints": put(J, np.uint32), "weights": put(W, np.float32)})
    doc = {"format": "pratibimb-anime 1", "unit": "m", "style": ch.style, "meshes": meshes, "morphNames": ch.names,
           "skeleton": {"names": S.names, "parents": S.parent, "rest": [p.tolist() for p in S.rest]},
           "colours": {k: v.tolist() for k, v in ch.colours.items()}, "headJoint": "head", "sex": ch.sex,
           "label": "AI-generated"}
    json.dump(doc, open(os.path.join(out, "character.json"), "w"))
    open(os.path.join(out, "character.bin"), "wb").write(bytes(blob))
    return doc


def tube_rest(t, S, Rw, Pw):
    """Rest-pose tube with skin weights: each ring follows the bone it lies on, blending into the next bone over
    the last fifth of the segment (smooth elbows and knuckles)."""
    from .body import tube_mesh
    V, F = tube_mesh(t, S, Rw, Pw)
    ids = [S.idx(n) for n in t.chain]
    pts = [Pw[i] for i in ids]
    seglen = [np.linalg.norm(pts[k + 1] - pts[k]) for k in range(len(pts) - 1)]
    total = sum(seglen) + 1e-9
    frac = getattr(t, "length", 1.0)
    J = np.zeros((len(V), 2), np.int64)
    W = np.zeros((len(V), 2))
    for r in range(t.rings):
        u = r / (t.rings - 1) * frac
        dd = u * total
        k = 0
        while k < len(seglen) - 1 and dd > seglen[k]:
            dd -= seglen[k]
            k += 1
        tt = min(1.0, dd / (seglen[k] + 1e-9))
        b = min(1.0, max(0.0, (tt - 0.8) / 0.2)) * 0.5 if k + 1 < len(ids) - 1 or True else 0.0
        nxt = ids[min(k + 1, len(ids) - 1)]
        sl = slice(r * t.seg, (r + 1) * t.seg)
        J[sl, 0], J[sl, 1] = ids[k], nxt
        W[sl, 0], W[sl, 1] = 1 - b, b
    for extra in range(t.rings * t.seg, len(V)):  # cap centres
        J[extra] = J[extra - 1]
        W[extra] = W[extra - 1]
    return V, F, J, W


def make_hair(ch, P0, attach):
    """Anime hair: a scalp cap plus locks. Locks are tapered blades with a ridge, curving down and out."""
    h = ch.hair
    face_w = np.abs(P0[OVAL][:, 0]).max() * 2
    top_y = P0[10][1]
    length = max(-0.9, min(2.5, float(h.get("length_below_chin_face_widths", -0.6) or -0.6)))
    volume = max(0.2, min(1.5, float(h.get("volume_face_areas", 0.6) or 0.6)))
    part = float(h.get("parting_offset", 0.0) or 0.0)
    chin_y = P0[152][1]
    end_y_side = chin_y - length * face_w  # where side and back locks end
    rng = np.random.default_rng(11)
    V, F = [], []
    centre = np.array([0, top_y - 0.04, P0[OVAL][:, 2].mean() - 0.085])
    rx, ry, rz = face_w / 2 * 1.12 + 0.01 * volume, 0.105 + 0.01 * volume, 0.11 + 0.012 * volume

    def scalp(theta, phi):  # theta: around (0 = front), phi: from the top
        return centre + np.array([rx * math.sin(phi) * math.sin(theta), ry * math.cos(phi), rz * math.sin(phi) * math.cos(theta)])

    # cap
    nt, npf = 28, 10
    base = len(V)
    for i in range(npf + 1):
        phi = (math.pi * 0.62) * i / npf
        for j in range(nt):
            th = 2 * math.pi * j / nt
            V.append(scalp(th, phi))
    for i in range(npf):
        for j in range(nt):
            a, b = base + i * nt + j, base + i * nt + (j + 1) % nt
            c2, d = a + nt, b + nt
            th = 2 * math.pi * j / nt
            if i > npf * 0.55 and (abs(math.sin(th / 2)) < 0.42):  # leave the face open at the front
                continue
            F += [(a, b, c2), (b, d, c2)]

    def lock(root, direction, length_m, width, curl):
        nonlocal V, F
        segs = 7
        pts, ws = [], []
        p = root.copy()
        d = direction / np.linalg.norm(direction)
        for k in range(segs + 1):
            pts.append(p.copy())
            ws.append(width * (1 - k / segs) ** 0.8 + 0.0008)
            d = d + np.array([0, -0.22, 0]) + curl * np.cross(d, [0, 1, 0]) * 0.12
            d = d / np.linalg.norm(d)
            p = p + d * length_m / segs
        out = np.array([pts[k][0] for k in range(len(pts))])  # noqa: F841
        b0 = len(V)
        for k, (q, w) in enumerate(zip(pts, ws)):
            tdir = pts[min(k + 1, segs)] - pts[max(k - 1, 0)]
            tdir = tdir / (np.linalg.norm(tdir) + 1e-12)
            radial = q - centre
            radial = radial / (np.linalg.norm(radial) + 1e-12)
            side = np.cross(tdir, radial)
            side = side / (np.linalg.norm(side) + 1e-12)
            V += [q + side * w, q + radial * w * 0.55, q - side * w]  # triangular section: a ridge on top
        for k in range(segs):
            for m in range(2):
                a, b = b0 + 3 * k + m, b0 + 3 * k + m + 1
                c2, d2 = a + 3, b + 3
                F += [(a, c2, b), (b, c2, d2)]

    # bangs over the forehead, split at the parting
    for j in range(9):
        x = -0.5 + j / 8
        if abs(x - part) < 0.06:
            continue
        th = x * 1.2
        root = scalp(th, 0.55)
        d = np.array([0.15 * math.copysign(1, x - part), -1.0, 0.55])
        lock(root, d, (P0[10][1] - P0[105][1]) + 0.018 + rng.uniform(0, 0.012), 0.016, 0.3 * math.copysign(1, x - part))
    # sides and back
    for j in range(22):
        th = math.pi * 0.42 + (math.pi * 2 - math.pi * 0.84) * j / 21
        root = scalp(th, 0.85 + rng.uniform(-0.1, 0.1))
        outward = root - centre
        outward[1] = 0
        d = outward / (np.linalg.norm(outward) + 1e-9) * 0.35 + np.array([0, -1.0, 0])
        L = max(0.05, (root[1] - end_y_side)) * (1.0 + rng.uniform(-0.12, 0.12))
        lock(root, d, L, 0.022 * (0.8 + 0.4 * volume), rng.uniform(-0.3, 0.3))
    return np.array(V) + attach, np.array(F, np.int64)


