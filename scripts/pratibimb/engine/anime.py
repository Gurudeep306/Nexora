"""Build the person's 3D anime character from their identity pack (docs/pratibimb/BRIEF.md).

  python3 -m engine.anime <pack.pbpack> <out dir> [--style 0.8] [--sex auto|female|male] [--outfit '{...}']

Everything is generated by this code from measurements; no photo pixel and no outside asset is used.

- Face: the person's own 3D face points (rig.py, their own expression model), stylised to anime by smooth
  local deformations (larger eyes, smaller nose, narrower mouth, softer jaw, flatter face) whose strength is
  --style (0 = their real proportions, 1 = full anime). Eye and mouth openings are cut, the back of the head
  is generated, and the head is smoothed by Loop subdivision.
- Every face-attached vertex (head, brows, lashes, mouth) is a fixed linear function of the 468 face points,
  so the person's 52 expressions become 52 morph targets of the whole head.
- Eyes, teeth, tongue: generated shapes; the anime eye look (iris, pupil, highlights) is drawn by the shader.
- Hair: anime locks (tapered, curved, triangular in section) grown from the scalp, shaped by the measured hair
  length, volume, width and parting, in the measured hair colour.
- Body and clothes: body.py (our skeleton and tubes), skinned to the bones.
Writes <out>/character.json + character.bin for the player (player/anime.html).
"""
