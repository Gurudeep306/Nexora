# --- small geometry helpers ---------------------------------------------------------------------------------
def loop_subdivide(F, nv):
    """Loop subdivision as a sparse linear operator: new_vertices = S @ old_vertices. Returns (S, new faces).
    Boundary edges (eye and mouth openings, head base) follow the boundary rules, so openings stay sharp."""
    edges = {}
    for t in F:
        for a, b, c in ((t[0], t[1], t[2]), (t[1], t[2], t[0]), (t[2], t[0], t[1])):
            e = (min(a, b), max(a, b))
            edges.setdefault(e, []).append(c)
    eid = {e: nv + k for k, e in enumerate(edges)}
    rows, cols, vals = [], [], []
    nbr = [set() for _ in range(nv)]
    bnbr = [set() for _ in range(nv)]
    for (a, b), opp in edges.items():
        nbr[a].add(b)
        nbr[b].add(a)
        if len(opp) == 1:
            bnbr[a].add(b)
            bnbr[b].add(a)
    for v in range(nv):
        if bnbr[v]:
            rows += [v] * (1 + len(bnbr[v]))
            cols += [v] + list(bnbr[v])
            vals += [0.75] + [0.125] * len(bnbr[v]) if len(bnbr[v]) == 2 else [1.0] + [0.0] * len(bnbr[v])
        else:
            n = len(nbr[v])
            beta = (5 / 8 - (3 / 8 + math.cos(2 * math.pi / max(n, 3)) / 4) ** 2) / max(n, 1)
            rows += [v] * (n + 1)
            cols += [v] + list(nbr[v])
            vals += [1 - n * beta] + [beta] * n
    for (a, b), opp in edges.items():
        r = eid[(a, b)]
        if len(opp) == 1:
            rows += [r, r]
            cols += [a, b]
            vals += [0.5, 0.5]
        else:
            rows += [r] * 4
            cols += [a, b, opp[0], opp[1]]
            vals += [3 / 8, 3 / 8, 1 / 8, 1 / 8]
    S = sps.csr_matrix((vals, (rows, cols)), shape=(nv + len(edges), nv))
    NF = []
    for a, b, c in F:
        ab, bc, ca = eid[(min(a, b), max(a, b))], eid[(min(b, c), max(b, c))], eid[(min(c, a), max(c, a))]
        NF += [(a, ab, ca), (b, bc, ab), (c, ca, bc), (ab, bc, ca)]
    return S, np.array(NF, np.int64)


def ribbon(line, widths, normal, lift=0.0):
    """A flat strip along a polyline: vertices (2n x 3) and faces."""
    line = np.asarray(line, np.float64)
    V, Fc = [], []
    for i, p in enumerate(line):
        d = line[min(i + 1, len(line) - 1)] - line[max(i - 1, 0)]
        d = d / (np.linalg.norm(d) + 1e-12)
        side = np.cross(normal, d)
        side = side / (np.linalg.norm(side) + 1e-12)
        V += [p + side * widths[i] / 2 + normal * lift, p - side * widths[i] / 2 + normal * lift]
    for i in range(len(line) - 1):
        a, b, c, d2 = 2 * i, 2 * i + 1, 2 * i + 2, 2 * i + 3
        Fc += [(a, c, b), (b, c, d2)]
    return np.array(V), np.array(Fc, np.int64)


def sphere(c, r, n=16):
    V, Fc = [], []
    for i in range(n + 1):
        th = math.pi * i / n
        for j in range(2 * n):
            ph = 2 * math.pi * j / (2 * n)
            V.append(c + r * np.array([math.sin(th) * math.cos(ph), math.cos(th), math.sin(th) * math.sin(ph)]))
    for i in range(n):
        for j in range(2 * n):
            a, b = i * 2 * n + j, i * 2 * n + (j + 1) % (2 * n)
            c2, d = a + 2 * n, b + 2 * n
            Fc += [(a, b, c2), (b, d, c2)]  # counter-clockwise seen from outside
    return np.array(V), np.array(Fc, np.int64)


