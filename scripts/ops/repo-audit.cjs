#!/usr/bin/env node
/*
  Repo audit: what is in the repository, what refers to it, and what looks
  unused, duplicated or generated. It only reports; it deletes nothing.

    node scripts/ops/repo-audit.cjs            # writes docs/ops/REPO_AUDIT.md
    node scripts/ops/repo-audit.cjs --json     # machine-readable, to stdout

  "Unreferenced" means no other tracked text file mentions the file's name
  (with or without its extension) or its path. Files loaded by folder (lesson
  content, figures, past papers, problem JSON) are judged as folders. A file
  listed here still needs a human look before it goes.
*/
const fs = require('fs')
const path = require('path')
const crypto = require('crypto')
const { execFileSync } = require('child_process')

const root = path.join(__dirname, '..', '..')
function isFile(f) {
  try {
    return fs.statSync(path.join(root, f)).isFile()
  } catch {
    return false
  }
}
// Tracked paths that are not plain files (a symlink to a folder, a missing file) are skipped.
const notFiles = []
const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: root })
  .toString()
  .split('\0')
  .filter(Boolean)
  .filter((f) => (isFile(f) ? true : (notFiles.push(f), false)))
const TEXT = /\.(c?js|mjs|ts|tsx|jsx|json|md|html|css|scss|yml|yaml|toml|txt|py|sh|cjs|svg|webmanifest|ini|env\.example|conf|Caddyfile)$|(^|\/)(Dockerfile|Caddyfile|Procfile|\.gitignore|\.dockerignore)$/i
const size = (f) => {
  try {
    return fs.statSync(path.join(root, f)).size
  } catch {
    return 0
  }
}

// Folders whose files are found by listing the folder, not by name.
const BY_FOLDER = [/^content\//, /^public\/gate-fig\//, /^GATE_PYQ\//, /^src\/learn\/problems\//, /^src\/gate\//, /^scripts\/learn\//, /^client\/public\/(avatars|covers|ai-py|gate-fig|brand)\//, /^tests\//, /^docs\//, /^\.github\//, /^client\/src\/learn\/content\//, /^src\/sources\//]
// Entry points and config files: used by tools, not referenced by name.
const ENTRY = /(^|\/)(package(-lock)?\.json|tsconfig[^/]*\.json|vite\.config\.ts|eslint[^/]*|\.oxlintrc\.json|README\.md|AGENTS\.md|CLAUDE\.md|LICENSE|render\.yaml|index\.html|main\.tsx|App\.tsx|server\.js|\.gitignore|\.gitattributes|\.nvmrc|\.env\.example|Procfile|manifest\.webmanifest|favicon\.(ico|svg)|robots\.txt|sw\.js)$/

const texts = new Map()
for (const f of tracked) if (TEXT.test(f) && size(f) < 3e6) texts.set(f, fs.readFileSync(path.join(root, f), 'utf8'))
const corpus = [...texts.entries()]

function referenced(f) {
  const base = path.basename(f)
  const stem = base.replace(/\.[^.]+$/, '')
  const needles = [base, f]
  // Module imports often drop the extension; only use the stem when it is distinctive.
  if (stem.length >= 6 || /^[A-Z]/.test(stem)) needles.push(stem)
  for (const [g, t] of corpus) {
    if (g === f) continue
    for (const n of needles) if (t.includes(n)) return g
  }
  return null
}

const unreferenced = []
for (const f of tracked) {
  if (BY_FOLDER.some((r) => r.test(f)) || ENTRY.test(f)) continue
  const by = referenced(f)
  if (!by) unreferenced.push({ file: f, bytes: size(f) })
}

// Exact duplicates (same bytes), above 4 KB.
const byHash = new Map()
for (const f of tracked) {
  const n = size(f)
  if (n < 4096) continue
  const h = crypto.createHash('sha1').update(fs.readFileSync(path.join(root, f))).digest('hex')
  byHash.set(h, [...(byHash.get(h) ?? []), f])
}
const duplicates = [...byHash.values()].filter((g) => g.length > 1).map((g) => ({ files: g, bytes: size(g[0]) }))

const large = tracked.map((f) => ({ file: f, bytes: size(f) })).filter((x) => x.bytes > 1e6).sort((a, b) => b.bytes - a.bytes)

const report = { tracked: tracked.length, notFiles, unreferenced, duplicates, large }
if (notFiles.length) console.error('tracked but not plain files:', notFiles.join(', '))
if (process.argv.includes('--json')) {
  process.stdout.write(JSON.stringify(report, null, 2))
} else {
  const mb = (b) => `${(b / 1048576).toFixed(2)} MB`
  const kb = (b) => (b > 1048576 ? mb(b) : `${Math.round(b / 1024)} KB`)
  const lines = [
    '# Repo audit',
    '',
    `Generated by \`scripts/ops/repo-audit.cjs\`. ${tracked.length} tracked files. This lists candidates only; nothing is deleted by it.`,
    '',
    `## Large files (over 1 MB): ${large.length}`,
    '',
    '| Size | File |',
    '|---|---|',
    ...large.map((x) => `| ${mb(x.bytes)} | \`${x.file}\` |`),
    '',
    `## Exact duplicates: ${duplicates.length} groups`,
    '',
    ...duplicates.map((d) => `- ${kb(d.bytes)} each: ${d.files.map((f) => `\`${f}\``).join(', ')}`),
    '',
    `## Not referenced by any other file: ${unreferenced.length}`,
    '',
    '| Size | File |',
    '|---|---|',
    ...unreferenced.sort((a, b) => b.bytes - a.bytes).map((x) => `| ${kb(x.bytes)} | \`${x.file}\` |`),
    '',
  ]
  fs.mkdirSync(path.join(root, 'docs/ops'), { recursive: true })
  fs.writeFileSync(path.join(root, 'docs/ops/REPO_AUDIT.md'), lines.join('\n'))
  console.log(`large ${large.length}, duplicate groups ${duplicates.length}, unreferenced ${unreferenced.length} → docs/ops/REPO_AUDIT.md`)
}
